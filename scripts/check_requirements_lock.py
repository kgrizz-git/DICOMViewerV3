#!/usr/bin/env python3
"""Fail when a committed ``requirements*.txt`` lock is stale or hand-edited.

The check copies the ``.in`` files and the committed ``.txt`` locks into a
scratch folder under the repo ``tmp/``, recompiles there with
``scripts/compile_requirements.py`` (same pinned uv, same relative command line,
so headers match), and compares bytes with the committed locks. The committed
locks are present in the scratch folder, so uv keeps their pins: a new PyPI
release alone never makes this check fail. Only a mismatch between a ``.in``
file and its lock does.

Network access to PyPI is needed, because uv must be able to resolve. The check
fails closed when it cannot.
"""

from __future__ import annotations

import argparse
import shutil
import sys
import tempfile
from pathlib import Path

try:
    from scripts import compile_requirements as cr
except ModuleNotFoundError:
    import compile_requirements as cr  # type: ignore[no-redef]

HEADER_PREFIX = "# This file was autogenerated by uv via the following command:"


def locked_files() -> list[str]:
    """Return every file the check reads: each ``.in`` and its ``.txt`` lock."""
    return [
        name
        for stem in cr.LOCK_STEMS
        for name in (cr.input_name(stem), cr.output_name(stem))
    ]


def has_uv_header(text: str, stem: str) -> bool:
    """Return whether the lock starts with uv's standard header and the expected command."""
    lines = text.splitlines()
    if len(lines) < 2 or lines[0] != HEADER_PREFIX:
        return False
    expected = "#    " + " ".join(cr.compile_command(stem))
    return lines[1] == expected


def differing_locks(committed: dict[str, str], fresh: dict[str, str]) -> list[str]:
    """Return lock file names whose committed text differs from the fresh compile."""
    return [
        cr.output_name(s)
        for s in cr.LOCK_STEMS
        if committed.get(cr.output_name(s)) != fresh.get(cr.output_name(s))
    ]


def read_locks(directory: Path) -> dict[str, str]:
    """Read every lock in ``directory``; a missing file is simply absent."""
    locks: dict[str, str] = {}
    for stem in cr.LOCK_STEMS:
        path = directory / cr.output_name(stem)
        if path.is_file():
            locks[path.name] = path.read_text(encoding="utf-8")
    return locks


def stage(repo_root: Path, scratch: Path) -> None:
    """Copy the ``.in`` files and committed locks into ``scratch``."""
    for name in locked_files():
        source = repo_root / name
        if source.is_file():
            shutil.copy2(source, scratch / name)


def check(repo_root: Path, *, uv: str = "uv") -> int:
    """Return 0 when every committed lock matches a fresh compile, else non-zero."""
    committed = read_locks(repo_root)
    missing = [
        cr.output_name(s) for s in cr.LOCK_STEMS if cr.output_name(s) not in committed
    ]
    if missing:
        print(f"Missing lock file(s): {', '.join(missing)}", file=sys.stderr)
        return 1
    bad_headers = [
        cr.output_name(s)
        for s in cr.LOCK_STEMS
        if not has_uv_header(committed[cr.output_name(s)], s)
    ]
    if bad_headers:
        print(
            f"Not a standard uv-generated lock (header missing or edited): {', '.join(bad_headers)}",
            file=sys.stderr,
        )
        return 1
    tmp_root = repo_root / "tmp"
    tmp_root.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=tmp_root, prefix="lockcheck-") as name:
        scratch = Path(name)
        stage(repo_root, scratch)
        status = cr.compile_all(scratch, uv=uv)
        if status != 0:
            print(
                "Could not recompile the locks; treating that as a failure.",
                file=sys.stderr,
            )
            return status
        stale = differing_locks(committed, read_locks(scratch))
    if stale:
        print(
            f"Stale or hand-edited lock(s): {', '.join(stale)}. "
            "Run: python scripts/compile_requirements.py",
            file=sys.stderr,
        )
        return 1
    print("requirements*.txt locks match their .in files.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.parse_args(argv)
    uv = shutil.which("uv") or "uv"
    found = cr.installed_uv_version(uv)
    if found != cr.UV_VERSION:
        print(f"Need uv=={cr.UV_VERSION} (found {found or 'none'}).", file=sys.stderr)
        return 1
    return check(Path(__file__).resolve().parent.parent, uv=uv)


if __name__ == "__main__":
    raise SystemExit(main())
